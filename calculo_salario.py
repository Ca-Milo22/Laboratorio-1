# Ejercicio: Calcula el pago total de un trabajador y su aporte del 4 %.
nombre = "Sara"
horas_trabajadas = 36
valor_por_hora = 20000.0

pago_total = horas_trabajadas * valor_por_hora

APORTE = 0.04
valor_aporte = pago_total * APORTE

print("Nombre:", nombre)
print("Horas trabajadas:", horas_trabajadas)
print("Valor por hora: $", valor_por_hora)
print("Pago total: $", pago_total)
print("Aporte 4%: $", valor_aporte)
